% CLINICAL CANDIDATES
% ========================================================================

    function result = ...
            detectClinicalCandidates(img,retinaMask)

        I = im2double(img);

        R = I(:,:,1);
        G = I(:,:,2);
        B = I(:,:,3);

        %% Bright candidates

        brightMap = ...
            0.45*R + ...
            0.40*G + ...
            0.15*B;

        brightMap = ...
            adapthisteq( ...
            mat2gray(brightMap));

        brightMask = ...
            brightMap > 0.82;

        brightMask = ...
            brightMask & retinaMask;

        brightMask = ...
            bwareaopen( ...
            brightMask, ...
            15);

        %% Dark candidates

        darkBase = ...
            mat2gray( ...
            0.50*R + ...
            0.35*G + ...
            0.15*B);

        background = ...
            imgaussfilt( ...
            darkBase, ...
            9);

        darkLocal = ...
            darkBase - background;

        darkMask = ...
            darkLocal < -0.060;

        darkMask = ...
            darkMask & retinaMask;

        darkMask = ...
            bwareaopen( ...
            darkMask, ...
            5);

        %% Red candidates

        redMap = ...
            R - ...
            0.70*G - ...
            0.20*B;

        redMask = ...
            redMap > 0.12;

        redMask = ...
            redMask & retinaMask;

        redMask = ...
            bwareaopen( ...
            redMask, ...
            6);

        %% Remove optic disc from bright candidates

        [~,discCenter] = ...
            detectOpticDisc( ...
            I, ...
            retinaMask);

        if ~isempty(discCenter)

            [X,Y] = meshgrid( ...
                1:size(I,2), ...
                1:size(I,1));

            discRadius = ...
                35;

            discRegion = ...
                (X-discCenter(1)).^2 + ...
                (Y-discCenter(2)).^2 < ...
                discRadius^2;

            brightMask(discRegion) = false;

        end

        %% Count

        brightCount = ...
            countRegions(brightMask);

        darkCount = ...
            countRegions(darkMask);

        redCount = ...
            countRegions(redMask);

        result.bright = min(brightCount,999);
        result.dark = min(darkCount,999);
        result.red = min(redCount,999);

        result.total = ...
            result.bright + ...
            result.dark + ...
            result.red;

        result.brightMask = brightMask;
        result.darkMask = darkMask;
        result.redMask = redMask;

    end

