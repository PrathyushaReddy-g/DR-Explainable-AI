    function uploadImage(~,~)

        [file,path] = uigetfile( ...
            {'*.png;*.jpg;*.jpeg;*.tif;*.tiff','Fundus Images'; ...
             '*.*','All Files'}, ...
            'Select Retinal Fundus Image');

        if isequal(file,0)
            return;
        end

        try

            img = imread(fullfile(path,file));

            if ndims(img) == 2
                img = repmat(img,[1 1 3]);
            end

            if size(img,3) > 3
                img = img(:,:,1:3);
            end

            if ~isa(img,'uint8')
                img = im2uint8(img);
            end

            state.image = img;
            state.fileName = string(file);

            resetAnalysis();

            imshow(state.image,'Parent',originalAxes);
            axis(originalAxes,'image');

            originalAxes.XTick = [];
            originalAxes.YTick = [];

            title(originalAxes,'Original Fundus Image');

            imshow(state.image,'Parent',qualityOriginalAxes);
            axis(qualityOriginalAxes,'image');

            qualityOriginalAxes.XTick = [];
            qualityOriginalAxes.YTick = [];

            title(qualityOriginalAxes,'Original Fundus Image');

            imshow(state.image,'Parent',explainOriginalAxes);
            axis(explainOriginalAxes,'image');

            explainOriginalAxes.XTick = [];
            explainOriginalAxes.YTick = [];

            title(explainOriginalAxes,'Original Fundus Image');

            cla(enhancedAxes);
            title(enhancedAxes,'Waiting for analysis');

            cla(camAxes);
            title(camAxes,'AI attention will appear here');

            cla(structureAxes);
            title(structureAxes,'Run analysis');

            cla(evidenceAxes);
            title(evidenceAxes,'Run analysis');

            cla(explainCAMAxes);
            title(explainCAMAxes,'Run analysis');

            statusLabel.Text = '● IMAGE LOADED';
            statusLabel.FontColor = BLUE;

            headerStatus.Text = '● IMAGE LOADED';

            pipelineLabel.Text = ...
                ['Image loaded: ' char(state.fileName) ...
                 ' → click Analyze Retina'];

            drawnow;

        catch ME

            uialert( ...
                fig, ...
                ['Unable to load image.' newline newline ...
                 ME.message], ...
                'Image Error');

        end

    end

%% ========================================================================
% ANALYSIS
% ========================================================================

function analyzeImage(~,~)

    if isempty(state.image)

        uialert( ...
            fig, ...
            'Please upload a fundus image first.', ...
            'No Image');

        return;
    end

    try

        %% ================================================================
        % START
        % ================================================================

        statusLabel.Text = '● ANALYZING';
        statusLabel.FontColor = ORANGE;

        headerStatus.Text = '● ANALYZING';

        pipelineLabel.Text = ...
            'Step 1/5: assessing image quality...';

        drawnow;


        %% ================================================================
        % STEP 1 — IMAGE QUALITY
        % ================================================================

        [quality,processed,info] = ...
            assessImageQualityLocal(state.image);

        state.processed = processed;

        state.qualityTotal = info.total;
        state.focusScore = info.focus;
        state.illuminationScore = info.illumination;
        state.fovScore = info.fov;
        state.contrastScore = info.contrast;
        state.qualityStatus = quality;

        updateQualityUI(quality,info);


        % Enhanced image is ONLY used for visualization and
        % retinal structure / clinical candidate analysis.

        imshow(processed,'Parent',enhancedAxes);
        axis(enhancedAxes,'image');

        enhancedAxes.XTick = [];
        enhancedAxes.YTick = [];

        title( ...
            enhancedAxes, ...
            'Enhanced Retinal View');


        imshow(processed,'Parent',qualityEnhancedAxes);
        axis(qualityEnhancedAxes,'image');

        qualityEnhancedAxes.XTick = [];
        qualityEnhancedAxes.YTick = [];

        title( ...
            qualityEnhancedAxes, ...
            'Enhanced Retinal View');


        %% ================================================================
        % STEP 2 — RETINAL STRUCTURE
        % ================================================================

        pipelineLabel.Text = ...
            'Step 2/5: analyzing retinal structures...';

        drawnow;


        state.retinaMask = ...
            createRetinaMask(state.image);


        [state.vesselMask,state.vesselDensity] = ...
            detectVessels( ...
            state.processed, ...
            state.retinaMask);


        [ ...
            state.opticDiscDetected, ...
            state.opticDiscCenter] = ...
            detectOpticDisc( ...
            state.processed, ...
            state.retinaMask);


        [ ...
            state.foveaEstimated, ...
            state.foveaCenter] = ...
            estimateFovea( ...
            state.processed, ...
            state.retinaMask, ...
            state.opticDiscCenter);


        updateStructureUI();


        %% ================================================================
        % STEP 3 — CLINICAL CANDIDATE EVIDENCE
        % ================================================================

        pipelineLabel.Text = ...
            'Step 3/5: detecting clinical candidate evidence...';

        drawnow;


        candidates = ...
            detectClinicalCandidates( ...
            state.processed, ...
            state.retinaMask);


        state.brightCandidates = candidates.bright;
        state.darkCandidates = candidates.dark;
        state.redCandidates = candidates.red;
        state.totalCandidates = candidates.total;

        state.brightMask = candidates.brightMask;
        state.darkMask = candidates.darkMask;
        state.redMask = candidates.redMask;


        updateEvidenceUI();


        %% ================================================================
        % STEP 4 — RESNET-18 CLASSIFICATION + GRAD-CAM
        % ================================================================

        pipelineLabel.Text = ...
            'Step 4/5: running ResNet-18 classification and Grad-CAM...';

        drawnow;


        if state.modelLoaded

            % ============================================================
            % IMPORTANT
            %
            % The trained ResNet-18 was trained/evaluated using ORIGINAL
            % fundus images.
            %
            % Therefore DO NOT send state.processed to the model.
            % ============================================================

            modelInputImage = state.image;


            [ ...
                grade, ...
                gradeIndex, ...
                confidence, ...
                probabilities, ...
                attention, ...
                attentionSource] = ...
                classifyWithModel( ...
                modelInputImage, ...
                state.trainedNet, ...
                state.classNames);

        else

            % ============================================================
            % FALLBACK
            % ============================================================

            [ ...
                grade, ...
                gradeIndex, ...
                confidence, ...
                probabilities, ...
                attention, ...
                attentionSource] = ...
                fallbackClassification( ...
                state.image, ...
                state.retinaMask, ...
                candidates);

        end


        %% ================================================================
        % SAVE MODEL RESULTS
        % ================================================================

        state.grade = grade;
        state.gradeIndex = gradeIndex;
        state.confidence = confidence;
        state.probabilities = probabilities;

        state.attentionMap = attention;
        state.attentionSource = attentionSource;


%% ================================================================
% REFERABLE DR DECISION
% ================================================================
%
% Grade 0 = No DR
% Grade 1 = Mild DR
% Grade 2 = Moderate DR
% Grade 3 = Severe DR
% Grade 4 = Proliferative DR
%
% The predicted DR grade is obtained directly from the ResNet-18
% class with the highest probability.
%
% For the dashboard screening decision:
% Moderate, Severe and Proliferative DR are considered referable.
%
% This keeps the displayed Grade and Referable decision consistent.

if numel(probabilities) >= 5

    % Probability of Moderate + Severe + Proliferative DR
    state.referableProbability = ...
        sum(probabilities(3:5));

else

    state.referableProbability = 0;

end


% Referral decision based on predicted DR grade

state.referable = ...
    state.gradeIndex >= 2;

        %% ================================================================
        % UPDATE RESULT PAGE
        % ================================================================

        updateResultUI();


        %% ================================================================
        % GRAD-CAM / ATTENTION MAP
        % ================================================================

        showAttention( ...
            state.image, ...
            state.attentionMap, ...
            camAxes, ...
            state.attentionSource);


        showAttention( ...
            state.image, ...
            state.attentionMap, ...
            explainCAMAxes, ...
            state.attentionSource);


        %% ================================================================
        % CLINICAL CANDIDATE MAP
        % ================================================================

        showCandidateMap( ...
            state.image, ...
            candidates, ...
            evidenceAxes);


        %% ================================================================
        % RETINAL STRUCTURE OVERLAY
        % ================================================================

        showStructureOverlay();


        %% ================================================================
        % STEP 5 — SCREENING RECOMMENDATION
        % ================================================================

        pipelineLabel.Text = ...
            'Step 5/5: preparing screening recommendation...';

        drawnow;


        updateRecommendation();


        %% ================================================================
        % UPDATE MAIN DASHBOARD
        % ================================================================

        updateDashboard();


        %% ================================================================
        % COMPLETE
        % ================================================================

        statusLabel.Text = ...
            '● SCREENING COMPLETE';

        statusLabel.FontColor = GREEN;

        headerStatus.Text = ...
            '● SCREENING COMPLETE';

        pipelineLabel.Text = ...
            'SCREENING COMPLETE: quality + structures + evidence + grading + XAI.';

        drawnow;


    catch ME

        statusLabel.Text = ...
            '● ANALYSIS ERROR';

        statusLabel.FontColor = RED;

        headerStatus.Text = ...
            '● ANALYSIS ERROR';

        pipelineLabel.Text = ...
            'Analysis stopped because an error occurred.';


        uialert( ...
            fig, ...
            ['Analysis failed:' newline newline ...
             ME.message], ...
            'Analysis Error');

    end

end
