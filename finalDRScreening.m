% ========================================================================

    function [vesselMask,density] = ...
            detectVessels(img,retinaMask)

        I = im2double(img);

        G = I(:,:,2);

        G = adapthisteq( ...
            G, ...
            'NumTiles',[8 8], ...
            'ClipLimit',0.02);

        vesselEnhancement = ...
            imbothat( ...
            G, ...
            strel('disk',4));

        pixels = ...
            vesselEnhancement(retinaMask);

        if isempty(pixels)

            vesselMask = ...
                false(size(retinaMask));

            density = 0;

            return;

        end

        threshold = graythresh(pixels);

        vesselMask = ...
            vesselEnhancement > ...
            max(0.01,0.80*threshold);

        vesselMask = ...
            vesselMask & retinaMask;

        vesselMask = ...
            bwareaopen( ...
            vesselMask, ...
            6);

        vesselMask = ...
            imclose( ...
            vesselMask, ...
            strel('disk',1));

        density = ...
            100*nnz(vesselMask) / ...
            max(1,nnz(retinaMask));

    end

%% ========================================================================
% OPTIC DISC
% ========================================================================

    function [detected,center] = ...
            detectOpticDisc(img,retinaMask)

        I = im2double(img);

        R = I(:,:,1);
        G = I(:,:,2);

        brightness = ...
            0.65*R + ...
            0.35*G;

        candidate = ...
            brightness > 0.70 & ...
            retinaMask;

        candidate = ...
            bwareaopen(candidate,100);

        detected = false;
        center = [];

        if nnz(candidate) == 0
            return;
        end

        CC = bwconncomp(candidate);

        stats = regionprops( ...
            CC, ...
            'Area', ...
            'Eccentricity', ...
            'Centroid');

        bestArea = 0;
        bestIndex = 0;

        for k = 1:numel(stats)

            area = stats(k).Area;

            eccentricity = ...
                stats(k).Eccentricity;

            if area >= 200 && ...
                    area <= 30000 && ...
                    eccentricity < 0.90 && ...
                    area > bestArea

                bestArea = area;
                bestIndex = k;

            end

        end

        if bestIndex > 0

            detected = true;

            center = ...
                stats(bestIndex).Centroid;

        end

    end

