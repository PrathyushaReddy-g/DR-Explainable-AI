    function txt = yesNo(value)

        if value
            txt = 'Yes';
        else
            txt = 'No';
        end

    end

    function txt = ternaryText(condition,a,b)

        if condition
            txt = a;
        else
            txt = b;
        end

    end

    function out = normalizeLogLocal(value,low,high)

        value = max(value,low);

        denominator = ...
            log10(high)-log10(low);

        if denominator <= 0

            out = 0;

            return;

        end

        out = ...
            (log10(value)-log10(low)) / ...
            denominator;

        out = ...
            min(1,max(0,out));

    end

