    function txt = ...
            getRecommendation(gradeIndex,quality)

        if quality == "POOR"

            txt = ...
                "IMAGE RECAPTURE RECOMMENDED. Improve focus, " + ...
                "illumination, contrast and retinal field of view " + ...
                "before relying on the screening result.";

            return;

        end

        switch gradeIndex

            case 0

                txt = ...
                    "No DR suspected. Routine screening follow-up " + ...
                    "is recommended, subject to clinical review.";

            case 1

                txt = ...
                    "Mild DR suspected. Clinical follow-up and " + ...
                    "ophthalmologist review are recommended.";

            case 2

                txt = ...
                    "Referable DR suspected. Ophthalmology referral " + ...
                    "is recommended.";

            case 3

                txt = ...
                    "Severe DR suspected. Prompt ophthalmology " + ...
                    "evaluation is recommended.";

            case 4

                txt = ...
                    "Proliferative DR suspected. Urgent ophthalmology " + ...
                    "evaluation is recommended.";

            otherwise

                txt = ...
                    "Clinical review recommended.";

        end

    end

