% RESNET-18 CLASSIFICATION
% ========================================================================

    function [ ...
            grade, ...
            gradeIndex, ...
            confidence, ...
            probs, ...
            attention, ...
            attentionSource] = ...
            classifyWithModel(img,net,classNames)

        inputSize = [224 224 3];

        try

            if isa(net,'dlnetwork')

                inputSize = net.Layers(1).InputSize;

            end

        catch

            inputSize = [224 224 3];

        end

        if numel(inputSize) < 3

            inputSize = ...
                [inputSize(1) inputSize(2) 3];

        end

        x = imresize( ...
            img, ...
            inputSize(1:2));

        if ndims(x) == 2

            x = repmat(x,[1 1 3]);

        end

        if size(x,3) > 3

            x = x(:,:,1:3);

        end

        x = im2single(x);

        scores = predict(net,x);

        if isa(scores,'dlarray')

            scores = extractdata(scores);

        end

        scores = gather(scores);

        scores = double(scores);

        scores = squeeze(scores);

        scores = scores(:);

        if numel(scores) < 5

            error( ...
                'The trained network returned fewer than five class scores.');

        end

        scores = scores(1:5);

        if all(isfinite(scores)) && ...
                all(scores >= 0) && ...
                abs(sum(scores)-1) < 0.05

            probs = ...
                scores / ...
                max(sum(scores),eps);

        else

            scores = ...
                scores - max(scores);

            expScores = exp(scores);

            probs = ...
                expScores / ...
                max(sum(expScores),eps);

        end

        probs = ...
            double(probs(:));

        [confidence,classIndex] = ...
            max(probs);

        classIndex = ...
            max(1,min(5,classIndex));

        gradeIndex = ...
            classIndex - 1;

        grade = ...
            string(classNames(classIndex));

        %% Grad-CAM

        attentionSource = "Grad-CAM";

        try

            attention = ...
                gradCAM( ...
                net, ...
                x, ...
                classIndex, ...
                OutputUpsampling="bicubic");

            if isa(attention,'dlarray')

                attention = ...
                    extractdata(attention);

            end

            attention = gather(attention);

            attention = double(attention);

            attention = squeeze(attention);

            if isempty(attention) || ...
                    all(~isfinite(attention(:)))

                error('Invalid Grad-CAM result.');

            end

            attention(~isfinite(attention)) = 0;

            attention = mat2gray(attention);

        catch

            gray = ...
                rgb2gray(im2double(img));

            attention = ...
                mat2gray(imgradient(gray));

            attentionSource = ...
                "Gradient attention fallback";

        end

    end

%% ========================================================================
% FALLBACK
% ========================================================================

    function [ ...
            grade, ...
            gradeIndex, ...
            confidence, ...
            probs, ...
            attention, ...
            attentionSource] = ...
            fallbackClassification(img,retinaMask,candidates)

        burden = ...
            0.02*candidates.dark + ...
            0.04*candidates.red + ...
            0.03*candidates.bright;

        burden = ...
            min(1,max(0,burden));

        if burden < 0.12

            gradeIndex = 0;

        elseif burden < 0.25

            gradeIndex = 1;

        elseif burden < 0.45

            gradeIndex = 2;

        elseif burden < 0.70

            gradeIndex = 3;

        else

            gradeIndex = 4;

        end

        names = [ ...
            "No DR", ...
            "Mild DR", ...
            "Moderate DR", ...
            "Severe DR", ...
            "Proliferative DR"];

        grade = names(gradeIndex+1);

        confidence = ...
            min(0.95,0.55+abs(burden-0.5));

        probs = zeros(5,1);

        probs(gradeIndex+1) = confidence;

        remaining = ...
            (1-confidence)/4;

        for k = 1:5

            if k ~= gradeIndex+1

                probs(k) = remaining;

            end

        end

        gray = ...
            rgb2gray(im2double(img));

        attention = ...
            mat2gray(imgradient(gray));

        attention(~retinaMask) = 0;

        attentionSource = ...
            "Gradient attention fallback";

    end

