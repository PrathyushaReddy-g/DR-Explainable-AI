% FOVEA ESTIMATION
% ========================================================================

    function [estimated,center] = ...
            estimateFovea(img,retinaMask,discCenter)

        estimated = false;
        center = [];

        if isempty(discCenter) || ...
                nnz(retinaMask) == 0

            return;

        end

        [h,w,~] = size(img);

        cx = discCenter(1);
        cy = discCenter(2);

        % Prototype geometric estimate:
        % fovea is estimated temporal to the optic disc.
        offsetX = ...
            0.25 * w;

        candidateX = ...
            cx + offsetX;

        candidateY = cy;

        candidateX = ...
            min(w-1,max(1,candidateX));

        candidateY = ...
            min(h-1,max(1,candidateY));

        if retinaMask( ...
                round(candidateY), ...
                round(candidateX))

            center = ...
                [candidateX candidateY];

            estimated = true;

        end

    end

