% QUALITY ASSESSMENT
% ========================================================================

    function [quality,processed,info] = ...
            assessImageQualityLocal(img)

        I = im2double(img);

        if ndims(I) == 2

            I = repmat(I,[1 1 3]);

        end

        if size(I,3) > 3

            I = I(:,:,1:3);

        end

        gray = rgb2gray(I);

        %% FOV

        retinaMask = gray > 0.035;

        retinaMask = imclose( ...
            retinaMask, ...
            strel('disk',8));

        retinaMask = imfill( ...
            retinaMask, ...
            'holes');

        if nnz(retinaMask) > 0

            retinaMask = ...
                bwareafilt(retinaMask,1);

        end

        fovFraction = ...
            double(nnz(retinaMask)) / ...
            double(numel(retinaMask));

        fovScore = ...
            100 * min( ...
            1, ...
            max( ...
            0, ...
            (fovFraction-0.15)/0.45));

        %% Focus

        laplacian = imfilter( ...
            gray, ...
            fspecial('laplacian',0.2), ...
            'replicate');

        focusPixels = ...
            double(laplacian(retinaMask));

        focusPixels = focusPixels(:);

        if isempty(focusPixels)

            focusRaw = 0;

        else

            focusMean = ...
                sum(focusPixels) / ...
                double(numel(focusPixels));

            centered = ...
                focusPixels - focusMean;

            focusRaw = ...
                sum(centered .* centered) / ...
                max(1,double(numel(focusPixels)-1));

        end

        focusScore = ...
            100 * normalizeLogLocal( ...
            focusRaw, ...
            1e-5, ...
            0.03);

        %% Illumination and contrast

        pixels = ...
            double(gray(retinaMask));

        pixels = pixels(:);

        if isempty(pixels)

            illuminationScore = 0;
            contrastRaw = 0;

        else

            meanBrightness = ...
                sum(pixels) / ...
                double(numel(pixels));

            brightnessScore = ...
                100 - ...
                min( ...
                100, ...
                abs(meanBrightness-0.45)*220);

            centered = ...
                pixels - meanBrightness;

            varianceValue = ...
                sum(centered .* centered) / ...
                max(1,double(numel(pixels)-1));

            variation = ...
                sqrt(max(0,varianceValue));

            uniformityScore = ...
                100 - ...
                min(100,variation*180);

            illuminationScore = ...
                0.65*brightnessScore + ...
                0.35*uniformityScore;

            contrastRaw = variation;

        end

        contrastScore = ...
            100 * min( ...
            1, ...
            max( ...
            0, ...
            (contrastRaw-0.04)/0.20));

        %% Total

        total = ...
            0.30*focusScore + ...
            0.25*illuminationScore + ...
            0.25*fovScore + ...
            0.20*contrastScore;

        total = ...
            min(100,max(0,total));

        if total >= 60

            quality = "GOOD";

        elseif total >= 45

            quality = "BORDERLINE";

        else

            quality = "POOR";

        end

        %% Enhancement

        green = I(:,:,2);

        greenCLAHE = adapthisteq( ...
            green, ...
            'NumTiles',[8 8], ...
            'ClipLimit',0.015);

        background = ...
            imgaussfilt( ...
            greenCLAHE, ...
            25);

        normalizedGreen = ...
            greenCLAHE ./ ...
            max(background,0.08);

        normalizedGreen = ...
            mat2gray(normalizedGreen);

        processed = I;

        processed(:,:,2) = normalizedGreen;

        %% Information

        info.total = total;
        info.focus = focusScore;
        info.illumination = illuminationScore;
        info.fov = fovScore;
        info.contrast = contrastScore;
        info.fovFraction = fovFraction;

    end

