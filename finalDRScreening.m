                base = repmat(base,[1 1 3]);

            end

            resizedMap = ...
                imresize( ...
                double(attention), ...
                size(base,[1 2]));

            resizedMap = ...
                mat2gray(resizedMap);

            cmap = turbo(256);

            mapIndex = ...
                max( ...
                1, ...
                min( ...
                256, ...
                round(resizedMap*255)+1));

            heat = ...
                ind2rgb( ...
                mapIndex, ...
                cmap);

            alpha = ...
                0.15 + ...
                0.60*resizedMap;

            alpha = ...
                min(0.75,max(0.15,alpha));

            alpha3 = ...
                repmat(alpha,[1 1 3]);

            blended = ...
                base .* (1-alpha3) + ...
                heat .* alpha3;

            blended = ...
                min(1,max(0,blended));

            imshow( ...
                blended, ...
                'Parent',ax);

            axis(ax,'image');

            ax.XTick = [];
            ax.YTick = [];

            title(ax,'AI Attention Map');

            camSourceLabel.Text = ...
                ['Attention status: ' char(source)];

            explainCAMSource.Text = ...
                ['Attention method: ' char(source)];

        catch

            imshow(img,'Parent',ax);

            title(ax,'Attention visualization');

        end

    end

